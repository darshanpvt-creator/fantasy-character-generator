import express, { Request, Response } from 'express';
import dotenv from 'dotenv';
import path from 'path';
import { fileURLToPath } from 'url';
import { GoogleGenAI } from '@google/genai';

dotenv.config();

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const app = express();
const port = Number(process.env.PORT) || 3000;

app.use(express.json({ limit: '10mb' }));

// Initialize GoogleGenAI client with server-side environment key
const apiKey = process.env.GEMINI_API_KEY || '';
const ai = apiKey ? new GoogleGenAI({ apiKey }) : null;

// POST /api/generate-portrait
app.post('/api/generate-portrait', async (req: Request, res: Response): Promise<void> => {
  try {
    const { name, characterClass, subclass, race, variationSeed } = req.body;

    if (!name || !characterClass) {
      res.status(400).json({ error: 'Name and characterClass are required' });
      return;
    }

    // Creative variation descriptors for "Regenerate Portrait"
    const variationStyles = [
      'dynamic heroic action stance, glowing eyes, cinematic rim lighting',
      'stoic close-up bust, intense gaze, atmospheric particle embers in background',
      'stylized profile view, confident smirk, vibrant magical aura',
      'dramatic three-quarter battle pose, ready for combat, high fantasy color saturation',
      'whimsical storybook game illustration, detailed facial features, bold outlines'
    ];

    const variation = variationStyles[
      (variationSeed || 0) % variationStyles.length
    ];

    const prompt = `A vibrant cartoon video game style fantasy character portrait of ${name}, a ${race || 'Fantasy'} ${characterClass} (${subclass || ''}). Stylized digital art, colorful RPG concept art, cartoon video game avatar, ${variation}, high quality, crisp details, centered composition, game UI avatar bust, square 1:1 format.`;

    if (!ai) {
      // Fallback if GEMINI_API_KEY is not configured yet
      res.status(503).json({
        error: 'GEMINI_API_KEY is not configured on the server. Please configure it in AI Studio Secrets.'
      });
      return;
    }

    const response = await ai.models.generateContent({
      model: 'gemini-3.1-flash-lite-image',
      contents: {
        parts: [{ text: prompt }]
      },
      config: {
        imageConfig: {
          aspectRatio: '1:1'
        }
      }
    });

    let imageUrl: string | null = null;
    const parts = response.candidates?.[0]?.content?.parts ?? [];
    for (const part of parts) {
      if (part.inlineData?.data) {
        const mime = part.inlineData.mimeType || 'image/png';
        imageUrl = `data:${mime};base64,${part.inlineData.data}`;
        break;
      }
    }

    if (!imageUrl) {
      res.status(500).json({ error: 'No image was generated by the model.' });
      return;
    }

    res.json({ imageUrl });
  } catch (err: unknown) {
    console.error('Error in /api/generate-portrait:', err);
    const message = err instanceof Error ? err.message : 'Failed to generate portrait';
    res.status(500).json({ error: message });
  }
});

// POST /api/generate-backstory
app.post('/api/generate-backstory', async (req: Request, res: Response): Promise<void> => {
  try {
    const { name, characterClass, subclass, race, alignment, quirk, motto } = req.body;

    if (!name || !characterClass) {
      res.status(400).json({ error: 'Name and characterClass are required' });
      return;
    }

    if (!ai) {
      res.status(503).json({
        error: 'GEMINI_API_KEY is not configured on the server.'
      });
      return;
    }

    const prompt = `Write a unique, compelling fantasy origin story of exactly one to two sentences for a character named "${name}", who is a ${race || 'Fantasy'} ${characterClass} (${subclass || ''}).
Their personality traits include:
- Alignment: ${alignment || 'Neutral'}
- Personal Quirk: "${quirk || ''}"
- Creed/Motto: "${motto || ''}"

Constraints:
1. Must be strictly 1 or 2 sentences in length.
2. Must match the character's name, class, and personality.
3. Evocative, immersive fantasy tone suitable for an RPG.
4. Do NOT include markdown headers, quotes, or preambles—return only the 1-2 sentences.`;

    const response = await ai.models.generateContent({
      model: 'gemini-3.8-flash',
      contents: prompt,
      config: {
        temperature: 0.85
      }
    });

    const backstory = response.text ? response.text.trim() : null;

    if (!backstory) {
      res.status(500).json({ error: 'Failed to generate backstory text' });
      return;
    }

    res.json({ backstory });
  } catch (err: unknown) {
    console.error('Error in /api/generate-backstory:', err);
    const message = err instanceof Error ? err.message : 'Failed to generate backstory';
    res.status(500).json({ error: message });
  }
});

// Vite middleware in dev or static files in production
async function startServer() {
  if (process.env.NODE_ENV === 'production') {
    const distPath = path.resolve(__dirname, 'dist');
    app.use(express.static(distPath));
    app.get('*', (_req, res) => {
      res.sendFile(path.resolve(distPath, 'index.html'));
    });
  } else {
    const { createServer } = await import('vite');
    const vite = await createServer({
      server: { middlewareMode: true },
      appType: 'spa',
    });
    app.use(vite.middlewares);
  }

  app.listen(port, '0.0.0.0', () => {
    console.log(`Server listening on http://0.0.0.0:${port}`);
  });
}

startServer().catch((err) => {
  console.error('Failed to start server:', err);
});
